import Link from "next/link";
import type { Metadata } from "next";
import { Activity, Filter, Radio, Search, ServerCog } from "lucide-react";
import { requireUser } from "@/lib/security/session";
import { listEvents } from "@/lib/repositories/events";
import { firstString, formatDateTime, formatRelativeTime } from "@/lib/utils";
import { parseSeverity } from "@/lib/validation/filters";
import { EVENT_SOURCES, SEVERITIES } from "@/types";
import { SEVERITY_CHART_COLORS, SEVERITY_LABELS } from "@/lib/constants";
import { PageHeader } from "@/components/ui/page-header";
import { Input, Select } from "@/components/ui/input";
import { Button, buttonClasses } from "@/components/ui/button";
import { EmptyState } from "@/components/ui/empty-state";
import { SeverityBadge } from "@/components/ui/badges";
import { SimulateEventsButton } from "@/components/events/simulate-events-button";
import type { EventSource } from "@/types";

export const metadata: Metadata = { title: "Security events" };

type SearchParams = Promise<Record<string, string | string[] | undefined>>;

function parseSource(value: string): EventSource | undefined {
  return EVENT_SOURCES.find((source) => source === value);
}

export default async function EventsPage({ searchParams }: { searchParams: SearchParams }) {
  const user = await requireUser();
  const params = await searchParams;
  const search = firstString(params.search).trim();
  const severity = parseSeverity(firstString(params.severity));
  const source = parseSource(firstString(params.source));

  const events = await listEvents({
    search: search || undefined,
    severity,
    source,
    limit: 200,
  });

  const filtered = Boolean(search || severity || source);
  const counts = SEVERITIES.map((option) => ({
    severity: option,
    count: events.filter((event) => event.severity === option).length,
  }));

  return (
    <div className="space-y-4">
      <PageHeader
        eyebrow="Telemetry"
        title="Security events"
        description="A unified activity stream from EDR, firewall, identity, WAF, scanner, and simulator sources. Events are context for findings, not detections from a connected sensor."
      >
        {user.role === "admin" ? <SimulateEventsButton /> : null}
      </PageHeader>

      <div className="flex items-start gap-2.5 rounded-xl border border-cyan-400/15 bg-cyan-400/[0.045] px-4 py-3">
        <Radio className="mt-0.5 size-4 shrink-0 text-cyan-300" aria-hidden="true" />
        <div>
          <p className="text-xs font-medium text-cyan-100">Demonstration telemetry</p>
          <p className="mt-0.5 text-[11px] leading-5 text-slate-400">
            Every event in this log is seeded sample data or generated by the simulator. Nothing is
            ingested from a real endpoint, firewall, or identity provider.
          </p>
        </div>
      </div>

      <div className="grid grid-cols-5 gap-2 sm:gap-3">
        {counts.map((entry) => (
          <div key={entry.severity} className="surface px-3 py-2.5">
            <div className="flex items-center gap-1.5">
              <span
                className="size-1.5 rounded-full"
                style={{ backgroundColor: SEVERITY_CHART_COLORS[entry.severity] }}
                aria-hidden="true"
              />
              <p className="font-mono text-base leading-none font-semibold text-slate-100 tabular-nums">
                {entry.count}
              </p>
            </div>
            <p className="mt-1.5 truncate text-[10px] text-slate-500">
              {SEVERITY_LABELS[entry.severity]}
            </p>
          </div>
        ))}
      </div>

      <form
        method="get"
        className="surface grid gap-2.5 p-3 md:grid-cols-[1fr_auto_auto_auto]"
        role="search"
        aria-label="Filter security events"
      >
        <div className="relative">
          <label htmlFor="event-search" className="sr-only">
            Search events
          </label>
          <Search
            className="pointer-events-none absolute top-1/2 left-3 size-3.5 -translate-y-1/2 text-slate-500"
            aria-hidden="true"
          />
          <Input
            id="event-search"
            name="search"
            defaultValue={search}
            placeholder="Search message, event type, source..."
            className="pl-9"
            maxLength={100}
          />
        </div>
        <div>
          <label htmlFor="event-severity-filter" className="sr-only">
            Filter by severity
          </label>
          <Select
            id="event-severity-filter"
            name="severity"
            defaultValue={severity ?? ""}
            className="md:w-40"
          >
            <option value="">All severities</option>
            {SEVERITIES.map((option) => (
              <option key={option} value={option}>
                {SEVERITY_LABELS[option]}
              </option>
            ))}
          </Select>
        </div>
        <div>
          <label htmlFor="event-source-filter" className="sr-only">
            Filter by source
          </label>
          <Select
            id="event-source-filter"
            name="source"
            defaultValue={source ?? ""}
            className="md:w-40"
          >
            <option value="">All sources</option>
            {EVENT_SOURCES.map((option) => (
              <option key={option} value={option}>
                {option}
              </option>
            ))}
          </Select>
        </div>
        <div className="flex gap-2">
          <Button type="submit" variant="secondary">
            <Filter className="size-3.5" aria-hidden="true" />
            Apply
          </Button>
          {filtered ? (
            <Link href="/events" className={buttonClasses("ghost", "md")}>
              Clear
            </Link>
          ) : null}
        </div>
      </form>

      {events.length === 0 ? (
        <EmptyState
          icon={filtered ? Search : Activity}
          title={filtered ? "No events match these filters" : "No security events recorded"}
          description={
            filtered
              ? "Try a different severity or source, or clear the search query."
              : user.role === "admin"
                ? "Generate sample telemetry to populate the event stream, or run the seed script to restore the demo dataset."
                : "Ask an administrator to generate sample telemetry or run the seed script."
          }
          action={
            filtered ? (
              <Link href="/events" className={buttonClasses("secondary", "sm")}>
                Clear filters
              </Link>
            ) : user.role === "admin" ? (
              <SimulateEventsButton />
            ) : undefined
          }
        />
      ) : (
        <div className="surface overflow-hidden">
          <div className="overflow-x-auto">
            <table className="w-full min-w-[880px] text-left">
              <thead>
                <tr className="border-b border-white/8 bg-white/[0.015]">
                  {["Severity", "Event", "Source", "Asset", "Occurred"].map((heading) => (
                    <th
                      key={heading}
                      scope="col"
                      className="px-4 py-2.5 font-mono text-[9px] font-medium tracking-wider text-slate-600 uppercase"
                    >
                      {heading}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody className="divide-y divide-white/[0.055]">
                {events.map((event) => (
                  <tr key={event.id} className="transition hover:bg-white/[0.02]">
                    <td className="px-4 py-3 align-top">
                      <SeverityBadge severity={event.severity} />
                    </td>
                    <td className="px-4 py-3 align-top">
                      <p className="max-w-[35rem] text-xs leading-5 text-slate-200">
                        {event.message}
                      </p>
                      <p className="mt-0.5 font-mono text-[9px] text-slate-600">
                        {event.eventType}
                      </p>
                    </td>
                    <td className="px-4 py-3 align-top">
                      <span className="font-mono text-[10px] text-slate-400">{event.source}</span>
                    </td>
                    <td className="px-4 py-3 align-top">
                      {event.assetId ? (
                        <Link
                          href={`/assets/${event.assetId}`}
                          className="inline-flex items-center gap-1 text-[11px] text-slate-400 transition hover:text-cyan-200"
                        >
                          <ServerCog className="size-3" aria-hidden="true" />
                          {event.assetName ?? "Unknown asset"}
                        </Link>
                      ) : (
                        <span className="text-[10px] text-slate-600">Unmapped</span>
                      )}
                    </td>
                    <td className="px-4 py-3 align-top">
                      <span
                        className="font-mono text-[10px] text-slate-400"
                        title={formatDateTime(event.occurredAt)}
                      >
                        {formatRelativeTime(event.occurredAt)}
                      </span>
                      <p className="mt-0.5 font-mono text-[9px] text-slate-600">
                        {event.occurredAt.slice(0, 16).replace("T", " ")}Z
                      </p>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="flex flex-wrap items-center justify-between gap-2 border-t border-white/8 px-4 py-2.5">
            <p className="font-mono text-[9px] text-slate-600">
              Showing {events.length} {events.length === 1 ? "event" : "events"}
              {filtered ? " matching filters" : ""} · limit 200
            </p>
            <p className="text-[9px] text-slate-600">Times shown in UTC.</p>
          </div>
        </div>
      )}

      <p className="px-1 pb-2 text-[10px] leading-5 text-slate-600">
        In a production deployment this view would read from a SIEM or event pipeline. Here, the
        simulator creates deterministic-looking sample telemetry so the workflow can be demonstrated
        safely.
      </p>
    </div>
  );
}
